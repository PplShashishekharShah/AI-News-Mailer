/**
 * Main function that runs the briefing
 */
async function runDailyBriefing() {
  try {
    console.log('\n' + '='.repeat(60));
    console.log('[' + new Date().toISOString() + '] Starting scheduled AI news briefing...');
    console.log('='.repeat(60) + '\n');

    // Step 1: Generate briefing
    console.log('Step 1/2: Generating AI news briefing with Groq (FREE API)...');
    console.log('(This may take 30-60 seconds - Groq is researching...\n');
    
    const briefing = await generateAINewsBriefing();
    
    if (!briefing) {
      throw new Error('No briefing content generated');
    }

    console.log('✓ Briefing generated successfully');
    console.log('Content preview (first 300 chars):');
    console.log(briefing.substring(0, 300) + '...\n');

    // Step 2: Send email
    console.log('Step 2/2: Sending email to ' + CONFIG.RECIPIENT_EMAIL + '...');
    await sendEmailBriefing(briefing);
    
    console.log('\n✓ Daily briefing completed successfully!');
    console.log('✓ Cost: $0 (Completely FREE using Groq)');
    console.log('✓ Next briefing: ' + getNextRunTime());
    console.log('='.repeat(60) + '\n');
  } catch (error) {
    console.error('\n✗ ERROR in daily briefing:');
    console.error(error.message);
    console.log('='.repeat(60) + '\n');
    
    // Send error notification email
    try {
      await transporter.sendMail({
        from: CONFIG.GMAIL_USER,
        to: CONFIG.RECIPIENT_EMAIL,
        subject: 'AI News Briefing - ERROR',
        text: `An error occurred while generating today's AI news briefing:\n\n${error.message}\n\nPlease check:\n1. Groq API key is correct (from console.groq.com)\n2. Gmail app password is correct\n3. Both are in the .env file`,
      });
    } catch (emailError) {
      console.error('Could not send error notification email:', emailError);
    }
  }
}

/**
 * Helper function to get next scheduled run time
 */
function getNextRunTime() {
  const nextDate = new Date();
  nextDate.setDate(nextDate.getDate() + 1);
  nextDate.setHours(8, 0, 0, 0);
  return nextDate.toLocaleString();
}

