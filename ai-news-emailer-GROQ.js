// Initialize Groq client (FREE!)
const groq = new Groq({
  apiKey: CONFIG.GROQ_API_KEY,
});

// Initialize Gmail transporter
const transporter = nodemailer.createTransport({
  service: 'gmail',
  auth: {
    user: CONFIG.GMAIL_USER,
    pass: CONFIG.GMAIL_APP_PASSWORD,
  },
});

/**
 * Function to generate AI news briefing using Groq (FREE API)
 */
async function generateAINewsBriefing() {
  console.log('[' + new Date().toISOString() + '] Starting AI news research with Groq (FREE)...');
  
  const newsPrompt = `You are an AI news analyst. Research and provide a comprehensive briefing on recent AI developments from the past 24 hours.

FOCUS ON:
1. New AI model releases and updates
2. Major AI company announcements (OpenAI, Anthropic, Google, Meta, Microsoft, etc.)
3. AI funding and investment news
4. AI regulatory and policy updates
5. Breakthroughs in AI research
6. Enterprise AI adoption news
7. Market trends and analysis

STRUCTURE YOUR RESPONSE EXACTLY AS FOLLOWS (this will be emailed):

---

# DAILY AI NEWS BRIEF
**Date:** ${new Date().toLocaleDateString('en-US', { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' })}
**Generated by:** Groq AI Analysis (Free API)

## 📊 MARKET & FUNDING NEWS
[List 2-3 significant funding rounds, acquisitions, or market movements with context]

## 🚀 NEW MODELS & FEATURE RELEASES
[List new AI models, APIs, or feature releases with what makes them noteworthy]

## 🏢 COMPANY ANNOUNCEMENTS
[Summarize major announcements from leading AI companies]

## 🔬 RESEARCH & BREAKTHROUGHS
[Highlight significant technical achievements or research papers from arXiv, DeepMind, OpenAI, Anthropic, etc.]

## ⚖️ REGULATORY & POLICY UPDATES
[Any government, regulatory, or policy changes affecting AI]

## 💡 KEY INSIGHTS & ANALYSIS
[Your professional analysis of what matters most - include market impact, trends, and what to watch]

## 📚 RECOMMENDED READING
[3-5 links/sources to read for more detail]

---

BE SPECIFIC:
- Include dates and numbers
- Mention specific companies and products
- Provide credible sources
- Be concise but comprehensive (aim for 2-3 pages when emailed)
- Focus on substantive news, not hype`;

  try {
    const message = await groq.chat.completions.create({
      messages: [
        {
          role: 'user',
          content: newsPrompt,
        },
      ],
      model: CONFIG.GROQ_MODEL,
      temperature: 0.7,
      max_tokens: 2000,
    });

    return message.choices[0]?.message?.content || '';
  } catch (error) {
    console.error('Error generating AI news briefing:', error);
    throw error;
  }
}

